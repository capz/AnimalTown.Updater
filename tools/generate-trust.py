#!/usr/bin/env python3
"""Generate immutable public TLS trust data without using the build host's CA store."""
import argparse
import base64
import hashlib
import json
from pathlib import Path
import re
import ssl

ROOT = Path(__file__).resolve().parents[1]
MAXIMUM_BYTES = 256 * 1024
CERTIFICATE = re.compile(rb'-----BEGIN CERTIFICATE-----\s+([A-Za-z0-9+/=\s]+?)-----END CERTIFICATE-----')


def load_bundle(directory=None):
    directory = Path(directory or ROOT / 'assets/https')
    manifest = json.loads((directory / 'source.json').read_text(encoding='utf-8'))
    if manifest.get('schema') != 1:
        raise ValueError('Unsupported trust-source manifest')
    source = manifest['source']
    content = (directory / 'cacert.pem').read_bytes()
    digest = hashlib.sha256(content).hexdigest()
    blob = hashlib.sha1(b'blob ' + str(len(content)).encode('ascii') + b'\0' + content).hexdigest()
    if len(content) != source['bytes'] or digest != source['sha256'] or blob != source['gitBlob']:
        raise ValueError('Pinned public CA source fingerprint mismatch')
    if not re.fullmatch(r'[0-9a-f]{40}', source['revision']):
        raise ValueError('Public CA source revision must be pinned')
    notice = (directory / 'LICENSE.certifi').read_bytes()
    if hashlib.sha256(notice).hexdigest() != manifest['licenseNoticeSha256']:
        raise ValueError('Public CA license notice fingerprint mismatch')
    blocks = []
    certificates = []
    for match in CERTIFICATE.finditer(content):
        block = b'\n'.join(line.strip() for line in match.group(0).splitlines())
        blocks.append(block)
        payload = re.sub(rb'\s+', b'', match.group(1))
        try:
            certificates.append(base64.b64decode(payload, validate=True))
        except ValueError as error:
            raise ValueError('Invalid public certificate encoding') from error
    bundle = b'\n'.join(blocks) + b'\n'
    if not blocks or len(bundle) > MAXIMUM_BYTES:
        raise ValueError('Embedded public CA bundle must contain certificates within 256 KiB')
    if len(set(certificates)) != len(certificates):
        raise ValueError('Duplicate public trust anchors')
    expected = manifest['embedded']
    if (len(bundle) != expected['bytes'] or len(blocks) != expected['certificates'] or
            hashlib.sha256(bundle).hexdigest() != expected['sha256']):
        raise ValueError('Embedded public CA bundle fingerprint mismatch')
    # This context starts empty. Never import the computer's system trust store
    # or a network proxy CA into a public game build.
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    try:
        context.load_verify_locations(cadata=bundle.decode('ascii'))
    except (UnicodeError, ssl.SSLError) as error:
        raise ValueError('Public CA bundle cannot be parsed') from error
    if context.cert_store_stats()['x509_ca'] != len(blocks):
        raise ValueError('Public CA bundle contains a non-CA or unparsed certificate')
    return bundle, manifest


def render(bundle, manifest):
    lines = [
        '// Generated by tools/generate-trust.py from the pinned Mozilla trust source.',
        '// Public certificates only: no private keys, entropy seeds or clock values.',
        '// Source and MPL-2.0 notice: assets/https/source.json and LICENSE.certifi.',
        'namespace AnimalTown.Updater;',
        '',
        'internal static class EmbeddedTrust',
        '{',
        '    internal const int CertificateCount=' + str(manifest['embedded']['certificates']) + ';',
        '    internal const int ByteLength=' + str(len(bundle)) + ';',
        '    internal const string Sha256="' + hashlib.sha256(bundle).hexdigest() + '";',
        '    // Roslyn emits a FieldRVA constant and InitializeArray. The native AOT',
        '    // image stores raw bytes once; callers own a bounded managed copy.',
        '    internal static byte[] LoadRoots()=>new byte[]{',
    ]
    for at in range(0, len(bundle), 16):
        lines.append('        ' + ','.join('0x%02x' % value for value in bundle[at:at + 16]) + ',')
    lines += ['    };', '}', '']
    return '\n'.join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='reject stale generated trust data')
    parser.add_argument('--source-directory', type=Path, default=ROOT / 'assets/https')
    parser.add_argument('--output', type=Path, default=ROOT / 'src/EmbeddedTrust.cs')
    options = parser.parse_args(argv)
    bundle, manifest = load_bundle(options.source_directory)
    expected = render(bundle, manifest)
    if options.check:
        if not options.output.is_file() or options.output.read_text(encoding='utf-8') != expected:
            raise SystemExit('Embedded public trust is stale; run python3 tools/generate-trust.py')
    else:
        options.output.parent.mkdir(parents=True, exist_ok=True)
        options.output.write_text(expected, encoding='utf-8', newline='\n')
    print('Embedded public trust verified: %d CA certificates, %d bytes, SHA256 %s' %
          (manifest['embedded']['certificates'], len(bundle), manifest['embedded']['sha256']))


if __name__ == '__main__':
    main()
